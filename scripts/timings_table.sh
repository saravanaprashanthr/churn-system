#!/usr/bin/env bash
# Build evidence/sql/timings.md from the benchmark CSVs written by scripts/benchmark.sh.
# Usage: scripts/timings_table.sh > evidence/sql/timings.md
set -euo pipefail

dir="evidence/sql"

cat <<'EOF'
# Part A timings

Generated by `scripts/timings_table.sh` from the CSVs in this folder (raw runs included).
Each value is `Execution Time` from `EXPLAIN (ANALYZE, TIMING OFF)` in ms.
**cold** = Postgres restarted and the Docker VM page cache dropped before every run;
**warm** = one discarded warm-up run, then the runs below. Data size is identical for every row
(customers 50,000 · orders 500,000 · order_items 1,530,225 · events 10,000,000; see `row_counts.txt`).

| Query | Version | Cache | Run 1 | Run 2 | Run 3 | Run 4 | Run 5 | **Median** |
|---|---|---|---:|---:|---:|---:|---:|---:|
EOF

for set in before naive_on_optimized_db after; do
  case "$set" in
    before)                version="naive, original schema" ;;
    naive_on_optimized_db) version="naive, optimized DB" ;;
    after)                 version="optimized" ;;
  esac
  tail -n +2 "$dir/benchmark_${set}.csv" | while IFS=, read -r query cache r1 r2 r3 r4 r5 median; do
    [[ "$query" == 92_events_time_window_no_brin ]] && version_row="no BRIN (bitmap scans off)" || version_row="$version"
    [[ "$query" == 14_events_time_window ]] && version_row="BRIN minmax_multi"
    echo "| \`$query\` | $version_row | $cache | $r1 | $r2 | $r3 | $r4 | $r5 | **$median** |"
  done
done
